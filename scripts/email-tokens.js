// Turns the CSS variables in src/styles/tokens.css and spacing.css into plain values for emails.
// Email apps (Gmail, Outlook) often ignore var() and external stylesheets, so every value
// has to be written inline as a real colour or pixel size. Output: src/lib/email/emailTokens.generated.ts
// Run: node scripts/email-tokens.js   (after npm run tokens)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const css = fs.readFileSync(path.join(root, "src/styles/tokens.css"), "utf8");
const spacing = fs.readFileSync(path.join(root, "src/styles/spacing.css"), "utf8");

const decls = (text) => Object.fromEntries([...text.matchAll(/^\s*(--[\w-]+):\s*(.+?);\s*$/gm)].map((m) => [m[1], m[2]]));
// palette block = first :root, light roles = the :root after the "Colour roles (light)" comment
const lightStart = css.indexOf("/* Colour roles (light)");
const lightBlock = css.slice(lightStart, css.indexOf("@media (prefers-color-scheme: dark)"));
const palette = decls(css.slice(0, lightStart));
const light = decls(lightBlock);
const type = decls(css.slice(css.indexOf("--type-display-large-family")));
const space = decls(spacing);

const colour = (role) => {
  const v = light[role]; const m = v && /^var\((--palette-[\w-]+)\)$/.exec(v);
  if (!m || !palette[m[1]]) throw new Error(`cannot resolve ${role}`);
  return palette[m[1]];
};
const px = (rem) => { const m = /^([\d.]+)rem$/.exec(rem); if (!m) throw new Error(`not rem: ${rem}`); return Math.round(parseFloat(m[1]) * 16); };
const t = (name) => ({
  weight: Number(type[`--type-${name}-weight`]), sizePx: px(type[`--type-${name}-size`]), linePx: px(type[`--type-${name}-line-height`]),
});
const out = {
  colour: Object.fromEntries(["surface", "surface-container-lowest", "on-surface", "on-surface-variant", "primary", "on-primary", "primary-container", "on-primary-container", "outline-variant"].map((r) => [r, colour(`--color-${r}`)])),
  type: { headline: t("headline-small"), title: t("title-medium"), body: t("body-large"), small: t("body-medium"), label: t("label-large") },
  spacePx: { 1: px(space["--space-1"]), 2: px(space["--space-2"]), 3: px(space["--space-3"]), 4: px(space["--space-4"]) },
  radiusPx: px(space["--radius"]),
};
const file = `// Generated by scripts/email-tokens.js from tokens.css and spacing.css. Do not edit by hand.\nexport const EMAIL_TOKENS = ${JSON.stringify(out, null, 2)} as const;\n`;
fs.writeFileSync(path.join(root, "src/lib/email/emailTokens.generated.ts"), file);
console.log(file);
